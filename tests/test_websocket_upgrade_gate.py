import pytest
import yaml

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
FRONTEND_YML = os.path.join(REPO, ".github", "workflows", "06-frontend-deploy.yml")

STEP_NAME = "Verify the WebSocket upgrade reaches the origin"


# ──────────────────────────────────────────────────────────────────────────────
#  Reading the workflow
# ──────────────────────────────────────────────────────────────────────────────

def _workflow():
    return yaml.safe_load(io.open(FRONTEND_YML, encoding="utf-8").read())


def _steps():
    return _workflow()["jobs"]["deploy-frontend"]["steps"]


def _gate_step():
    matches = [s for s in _steps() if (s.get("name") or "") == STEP_NAME]
    assert matches, "06-frontend-deploy.yml has no %r step; the realtime layer is ungated" % STEP_NAME
    return matches[0]


def _gate_body():
    return _gate_step()["run"]


def _workflow_text():
    return io.open(FRONTEND_YML, encoding="utf-8").read()


