# ──────────────────────────────────────────────────────────────────────────────
#  The step's behaviour, by running its real bash against stubbed curl
# ──────────────────────────────────────────────────────────────────────────────

def _curl_invocations(body):
    """Each real `curl` invocation as one logical line, backslash continuations joined.

    Both probes are of the form `VAR=$(curl ... || true)`, so matching on `$(curl ` picks up
    the invocations and skips the `curl -i ...` reproduction command the failure branch echoes
    for a human.
    """
    joined = body.replace("\\\n", " ")
    out = []
    for line in joined.splitlines():
        stripped = " ".join(line.split())
        if stripped.startswith("#") or stripped.startswith("echo "):
            continue
        if "$(curl " in stripped:
            out.append(stripped)
    return out


def _pass_condition(body):
    """The gate's pass test must be the CONJUNCTION of the two probes' inferences."""
    marker = 'if [ "$A_REACHED_ORIGIN" -eq 1 ] && [ "$B_ORIGIN_ANSWERED" -eq 1 ]; then'
    assert marker in body, (
        "the gate's pass condition is not the conjunction of both probes' inferences; either "
        "probe alone is insufficient"
    )
    return marker


def _accepted_upgrade_statuses(body):
    """The `case` that decides whether probe A reached the ASGI WebSocket router."""
    marker = 'case "$CODE_A" in'
    assert marker in body, "the gate does not classify the upgrade probe's status"
    return body.split(marker, 1)[1].split("esac", 1)[0]


def _stripped_header_branch(body):
    """The whole `if CODE_A = 404` branch, up to and including its closing `fi`."""
    marker = 'if [ "$CODE_A" = "404" ]; then'
    assert marker in body, (
        "no 404-on-probe-A branch: a stripped upgrade arrives at the origin as a plain GET and "
        "is HTTP-routed to 404, so this is the shape of the failure the gate exists to catch"
    )
    tail = body.split(marker, 1)[1]
    end = tail.find("\nfi\n")
    assert end != -1, "the 404-on-probe-A branch is never closed"
    return tail[:end]


def _bash_candidates():
    candidates = []
    explicit = os.environ.get("BASH_FOR_TESTS")
    if explicit:
        candidates.append(explicit)
    # Git for Windows ships a bash that understands Windows working directories natively.
    git = shutil.which("git")
    if git:
        git_root = os.path.dirname(os.path.dirname(os.path.abspath(git)))
        candidates.append(os.path.join(git_root, "bin", "bash.exe"))
    candidates.append(r"C:\Program Files\Git\bin\bash.exe")
    found = shutil.which("bash")
    if found:
        candidates.append(found)
    seen = set()
    ordered = []
    for c in candidates:
        if c and c not in seen and os.path.exists(c):
            seen.add(c)
            ordered.append(c)
    return ordered


def _bash_works(path):
    """The harness needs a bash that can run a relative script in a given cwd and that has the
    coreutils the step uses."""
    try:
        with tempfile.TemporaryDirectory() as tmp:
            with open(os.path.join(tmp, "probe.sh"), "wb") as fh:
                fh.write(b'printf "x 7 y\\n" | head -1 | tr -d "\\r" | awk "{print \\$2}"\n'
                         b'echo "wss://h" | sed -E "s#^wss?://##"\n'
                         b'echo ok | grep -qiE "^ok" && echo FINE\n')
            proc = subprocess.run([path, "probe.sh"], cwd=tmp, capture_output=True, timeout=60)
            return proc.returncode == 0 and b"FINE" in proc.stdout and b"7" in proc.stdout
    except Exception:
        return False


def _pick_bash():
    for candidate in _bash_candidates():
        if _bash_works(candidate):
            return candidate
    return None


BASH = _pick_bash()

needs_bash = pytest.mark.skipif(
    BASH is None,
    reason="no bash able to run the step's script was found; the text assertions above still "
           "pin the gate's logic (CI runs this job on ubuntu-latest, where bash is native)",
)

CRLF = chr(13) + chr(10)

# Measured, not invented. `UPGRADE_403` is the byte shape a local uvicorn returns for a
# minimal ASGI app that sends websocket.close before websocket.accept, with no CDN and no ALB;
# it is also what a raw upgrade to the ALB returns with CloudFront bypassed. Note the absence
# of a `server` header -- that absence is the whole point of this file.
UPGRADE_403 = [
    "HTTP/1.1 403 Forbidden",
    "Date: Fri, 02 Oct 2026 18:23:46 GMT",
    "Content-Type: text/plain",
    "Content-Length: 0",
    "Connection: close",
    "X-Cache: Error from cloudfront",
    "Via: 1.1 77a9d226db7a6fccf3907a64ecc724b4.cloudfront.net (CloudFront)",
]

# The no-upgrade GET, as observed through CloudFront against the live host. `X-Cache: Error
# from cloudfront` is on this one too, which is why it is not usable as a discriminator.
PLAIN_404_UVICORN = [
    "HTTP/1.1 404 Not Found",
    "Content-Type: application/json",
    "Content-Length: 22",
    "Connection: close",
    "x-request-id: 54ed67b32df640d99eeebbef2a58d6d1",
    "server: uvicorn",
    "X-Cache: Error from cloudfront",
]

UPGRADE_101 = [
    "HTTP/1.1 101 Switching Protocols",
    "Upgrade: websocket",
    "Connection: Upgrade",
    "Sec-WebSocket-Accept: s3pPLMBiTxaQ9kYGzzhZRbK+xOo=",
]

# What a stripped upgrade looks like: the handshake arrived as a plain GET and was HTTP-routed.
UPGRADE_STRIPPED_404 = list(PLAIN_404_UVICORN)

UPGRADE_502_CDN = [
    "HTTP/1.1 502 Bad Gateway",
    "Content-Type: text/html",
    "X-Cache: Error from cloudfront",
]

PLAIN_403_NO_ORIGIN = [
    "HTTP/1.1 403 Forbidden",
    "Content-Type: text/html",
    "Content-Length: 919",
    "X-Cache: Error from cloudfront",
]

# `curl` is shadowed by a shell function rather than a file on PATH: no chmod, no PATH
# rewriting, no path translation, and the real step body is left completely untouched.
HARNESS_PREAMBLE = """\
curl() {
  for _arg in "$@"; do
    if [ "$_arg" = "Upgrade: websocket" ]; then
      cat ./stub_upgrade.txt
      return 0
    fi
  done
  cat ./stub_plain.txt
  return 0
}
"""


def _write_headers(path, lines):
    with open(path, "wb") as fh:
        if lines:
            fh.write((CRLF.join(lines) + CRLF + CRLF).encode("ascii"))


def run_gate(upgrade_headers, plain_headers, bundle='connect("wss://app.vyomquant.in/ws/telemetry")'):
    """Run the shipped step body with curl stubbed. Returns (returncode, combined output)."""
    body = _gate_body()
    with tempfile.TemporaryDirectory() as tmp:
        assets = os.path.join(tmp, "dist", "assets")
        os.makedirs(assets)
        with open(os.path.join(assets, "index-a1b2c3d4.js"), "wb") as fh:
            fh.write(bundle.encode("utf-8"))

        _write_headers(os.path.join(tmp, "stub_upgrade.txt"), upgrade_headers)
        _write_headers(os.path.join(tmp, "stub_plain.txt"), plain_headers)

        with open(os.path.join(tmp, "gate.sh"), "wb") as fh:
            fh.write((HARNESS_PREAMBLE + body).replace("\r\n", "\n").encode("utf-8"))

        # `-e` is what GitHub Actions uses for a `run:` step on Linux.
        proc = subprocess.run(
            [BASH, "-e", "gate.sh"], cwd=tmp, capture_output=True, timeout=180
        )
    output = (proc.stdout + proc.stderr).decode("utf-8", "replace")
    return proc.returncode, output


@needs_bash
class TestTheGatePassesWhenTheRealtimeLayerIsHealthy:
    def test_a_403_with_no_server_header_plus_a_404_uvicorn_passes(self):
        """The production state of run 37035482811. The gate used to fail here."""
        code, out = run_gate(UPGRADE_403, PLAIN_404_UVICORN)
        assert code == 0, "the gate failed on a healthy realtime layer:\n%s" % out
        assert "✅" in out
        assert "Corroborated by probe B" in out

    def test_an_accepted_handshake_passes(self):
        code, out = run_gate(UPGRADE_101, PLAIN_404_UVICORN)
        assert code == 0, out
        assert "101 Switching Protocols" in out

    def test_the_pass_still_says_what_it_has_not_proven(self):
        code, out = run_gate(UPGRADE_403, PLAIN_404_UVICORN)
        assert code == 0, out
        assert "NOT PROVEN" in out, (
            "a passing run should not leave a reader believing a socket was shown to carry data"
        )


@needs_bash
class TestTheGateFailsWhenItShould:
    def test_a_stripped_upgrade_fails_and_names_the_cloudfront_misconfiguration(self):
        """Probe A degenerates into probe B: the regression this gate exists to catch."""
        code, out = run_gate(UPGRADE_STRIPPED_404, PLAIN_404_UVICORN)
        assert code == 1, "a stripped upgrade passed the gate:\n%s" % out
        assert "STRIPPED" in out
        assert "AllViewer" in out, "the correct remediation was not printed for this failure"

    def test_an_unreachable_origin_fails_without_blaming_cloudfront_headers(self):
        """Probe A looks fine but probe B cannot corroborate it. Different failure, different
        message -- and crucially NOT the header-forwarding advice."""
        code, out = run_gate(UPGRADE_403, PLAIN_403_NO_ORIGIN)
        assert code == 1, "the gate passed with no corroboration from probe B:\n%s" % out
        assert "could not be confirmed reachable" in out
        assert "AllViewer" not in out, (
            "the CloudFront header-forwarding remediation was printed for a failure whose "
            "evidence does not point there; that sends the next reader to reconfigure "
            "infrastructure that is already correct"
        )

    def test_a_missing_server_header_on_probe_b_alone_is_not_enough(self):
        plain_no_server = [h for h in PLAIN_404_UVICORN if not h.lower().startswith("server:")]
        code, out = run_gate(UPGRADE_403, plain_no_server)
        assert code == 1, "a 404 without `server: uvicorn` corroborated nothing:\n%s" % out
        assert "AllViewer" not in out

    def test_a_cdn_error_is_reported_as_itself(self):
        code, out = run_gate(UPGRADE_502_CDN, PLAIN_404_UVICORN)
        assert code == 1, out
        assert "cannot read as a handshake outcome" in out
        assert "AllViewer" not in out, (
            "a 502 is not evidence of stripped headers; the remediation must not be printed"
        )

    def test_an_empty_ws_base_in_the_bundle_still_fails(self):
        code, out = run_gate(UPGRADE_403, PLAIN_404_UVICORN, bundle="var x=1;// no socket url")
        assert code == 1, "the empty-WS_BASE guard no longer holds:\n%s" % out
        assert "No WebSocket base URL" in out


@needs_bash
def test_the_two_probes_are_both_actually_issued():
    """A gate that silently stopped sending one probe would still pass the text assertions if
    the dead code were left in place. Count the stub's invocations instead."""
    body = _gate_body()
    counting_preamble = """\
curl() {
  for _arg in "$@"; do
    if [ "$_arg" = "Upgrade: websocket" ]; then
      echo "PROBE_A_ISSUED" >> ./calls.txt
      cat ./stub_upgrade.txt
      return 0
    fi
  done
  echo "PROBE_B_ISSUED" >> ./calls.txt
  cat ./stub_plain.txt
  return 0
}
"""
    with tempfile.TemporaryDirectory() as tmp:
        assets = os.path.join(tmp, "dist", "assets")
        os.makedirs(assets)
        with open(os.path.join(assets, "index-a1b2c3d4.js"), "wb") as fh:
            fh.write(b'u="wss://app.vyomquant.in/ws"')
        _write_headers(os.path.join(tmp, "stub_upgrade.txt"), UPGRADE_403)
        _write_headers(os.path.join(tmp, "stub_plain.txt"), PLAIN_404_UVICORN)
        with open(os.path.join(tmp, "gate.sh"), "wb") as fh:
            fh.write((counting_preamble + body).replace("\r\n", "\n").encode("utf-8"))
        proc = subprocess.run([BASH, "-e", "gate.sh"], cwd=tmp, capture_output=True, timeout=180)
        calls_path = os.path.join(tmp, "calls.txt")
        calls = io.open(calls_path, encoding="utf-8").read() if os.path.exists(calls_path) else ""

    out = (proc.stdout + proc.stderr).decode("utf-8", "replace")
    assert "PROBE_A_ISSUED" in calls, "the upgrade probe was never sent:\n%s" % out
    assert "PROBE_B_ISSUED" in calls, "the no-upgrade probe was never sent:\n%s" % out
    assert proc.returncode == 0, out
