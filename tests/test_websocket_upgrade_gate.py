"""tests/test_websocket_upgrade_gate.py

The frontend deploy's WebSocket gate fails when the realtime layer is broken, and
passes when it is not.

THE GAP THIS CLOSES
-------------------
``06-frontend-deploy.yml``'s last step probes ``/ws/telemetry`` with a real HTTP/1.1 upgrade
and is BLOCKING, so it is the only thing standing between a silently-dead socket layer and a
green deploy. It is also the only step in that workflow whose verdict depends on a fact about
the ASGI server rather than on a fact about the bundle, and it got that fact wrong: it required
``server: uvicorn`` on the upgrade response as proof the origin had answered.

uvicorn does not emit a ``server`` header on that path. ``backend_app/api_ws/ws_routes.py``
closes before ``accept()`` when the ``ticket`` query parameter is absent, and uvicorn renders
that as a bare 403 with ``Content-Type: text/plain``, ``Content-Length: 0`` and no ``server``
header at all - reproduced on a local uvicorn running a minimal ASGI app with no CDN and no ALB
in the path, and identical in shape to what a raw upgrade straight to the ALB returns with
CloudFront bypassed. So the discriminator could never be satisfied: the gate failed every run,
run 37035482811 among them, and the state it reported as its failure ("403 with no origin
header") is the healthy one. The live frontend bundle went stale because no frontend change
could ship.

A FALSE-POSITIVE GATE IS A SPECIFIC KIND OF REGRESSION RISK
-----------------------------------------------------------
The obvious repair - drop the header condition and pass on any 403 - inverts into the opposite
defect, because a 403 generated by the CDN and a 403 from the application's WebSocket router are
the same status with the same headers. The gate has to keep BOTH probes to stay sound:

    A  genuine HTTP/1.1 upgrade  -> 403 (or 101); only reachable if the upgrade headers
                                    survived to the origin
    B  the same URL, no upgrade  -> 404 with ``server: uvicorn``; the origin's own fingerprint,
                                    which is what makes A's 403 attributable

and ``404`` on probe A has to stay a FAILURE, because that is what the regression looks like:
a stripped upgrade arrives at the origin as a plain GET and gets HTTP-routed.

WHAT THIS FILE PINS
-------------------
1. The TEXT of the step, so it cannot regress to the inverted form: two probes, ``404`` on the
   upgrade probe treated as failure, and no ``server``-header condition on the upgrade
   response's pass.
2. The step's actual BEHAVIOUR, by extracting its bash out of the YAML and running it with
   ``curl`` stubbed to canned header blocks. The workflow cannot be run locally, so this is the
   strongest cover available: it exercises the real shipped script, not a transcription of it.

Companion to ``tests/test_security_gate_blocks_deploy.py`` (task 13.10), which pins the other
blocking CI gate in this repository.
"""

import io
import os
import shutil
import subprocess
