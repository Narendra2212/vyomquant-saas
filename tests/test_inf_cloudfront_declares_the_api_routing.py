"""terraform/cloudfront.tf declares the API routing the live distribution actually has.

THE DEFECT THIS GUARDS
    The live CloudFront distribution (EEOXECPHQ8SR0) serves the SPA from S3 and routes five
    path patterns to the API's load balancer. terraform/cloudfront.tf declared only the S3
    origin and one default_cache_behavior: no ALB origin, no ordered_cache_behavior, no
    aliases, and the CloudFront default certificate.

    Nothing in terraform/ is applied -- the configured backend has no state object, a
    HeadObject on s3://vyomquant-terraform-state/prod/terraform.tfstate returns 404 -- so an
    `apply` on empty state would only have built a parallel stack and collided on existing
    names. Wasteful, not fatal.

    The fatal path was the realistic one: `terraform import` of the live distribution
    followed by `apply`. That reconciles live DOWN to the file, which would have deleted the
    ALB origin, all five API behaviours, all three aliases and the ACM certificate -- taking
    the whole API and websocket surface off the CDN and reverting the custom domain to the
    CloudFront default name.

WHY A TEST AND NOT JUST A COMMENT
    The comment explains; it does not hold. The five patterns are the contract between the
    CDN and the API, and a path silently dropped from the list is indistinguishable from a
    path that was never needed. This file makes that difference fail.

WHY THE EXPECTED SET IS PINNED HERE RATHER THAN READ FROM AWS
    Tests must pass offline and in CI, which holds no AWS credentials. The set below was
    READ FROM THE LIVE DISTRIBUTION, not designed:

        aws cloudfront get-distribution-config --id EEOXECPHQ8SR0

    If production's routing legitimately changes, this list changes with it in the same
    commit, which is the review signal that should exist for a change of that kind.
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
CLOUDFRONT_TF = REPO / "terraform" / "cloudfront.tf"

#: Read from the live distribution. ORDER IS PRECEDENCE: CloudFront takes the first match,
#: so this is a sequence and not a set.
EXPECTED_API_PATH_PATTERNS = [
    "/ws/*",
    "/api/*",
    "/health*",
    "/metrics*",
    "/openapi.json",
]

#: The origin id those behaviours target, as it exists live.
EXPECTED_ALB_ORIGIN_ID = "ALB-vyomquant-backend"


@pytest.fixture(scope="module")
def tf() -> str:
    assert CLOUDFRONT_TF.exists(), f"{CLOUDFRONT_TF} is missing"
    return CLOUDFRONT_TF.read_text(encoding="utf-8")


def _declared_patterns(tf: str) -> list[str]:
    """The path patterns in `locals.cdn_api_path_patterns`, in declaration order.

    Read from the locals list rather than from the behaviour blocks because the behaviours
    are generated by a `dynamic` block over exactly this list -- so the list IS the set of
    behaviours, and parsing it keeps the test honest about where the single source of truth
    lives. A future refactor that writes five literal blocks instead will fail here, which
    is the right outcome: it would reintroduce the two-places-to-forget problem.
    """
    match = re.search(
        r"cdn_api_path_patterns\s*=\s*\[(.*?)\]", tf, re.DOTALL
    )
    assert match, (
        "locals.cdn_api_path_patterns is gone from terraform/cloudfront.tf. The API path "
        "patterns are the contract between the CDN and the API; if they have moved, point "
        "this test at wherever they now live rather than deleting the check."
    )
    return re.findall(r'"([^"]+)"', match.group(1))


def test_every_api_path_pattern_is_declared_in_order(tf: str) -> None:
    assert _declared_patterns(tf) == EXPECTED_API_PATH_PATTERNS, (
        "terraform/cloudfront.tf no longer declares the live distribution's API path "
        "patterns in order.\n"
        f"  declared: {_declared_patterns(tf)}\n"
        f"  live    : {EXPECTED_API_PATH_PATTERNS}\n"
        "ORDER MATTERS -- CloudFront takes the first matching behaviour. A missing pattern "
        "means that path falls through to the S3 default behaviour and is answered with "
        "the SPA's index.html instead of by the API."
    )


def test_the_alb_origin_exists_and_the_behaviours_target_it(tf: str) -> None:
    assert f'alb_origin_id = "{EXPECTED_ALB_ORIGIN_ID}"' in tf, (
        f"locals.alb_origin_id is not {EXPECTED_ALB_ORIGIN_ID!r}. The behaviours and the "
        "origin are tied together through that local precisely so they cannot drift apart."
    )
    # An origin block that points at the load balancer, not only the S3 bucket.
    assert "aws_lb.main.dns_name" in tf, (
        "no origin in terraform/cloudfront.tf points at aws_lb.main. Without an ALB origin "
        "there is nothing for the API behaviours to target, and an import-then-apply would "
        "delete the live one."
    )
    assert "custom_origin_config" in tf, (
        "the ALB origin has no custom_origin_config. An ALB is a custom origin; declaring "
        "it without one is not a valid CloudFront origin."
    )
    assert "target_origin_id = local.alb_origin_id" in tf, (
        "the generated behaviours do not target local.alb_origin_id."
    )


def test_api_responses_are_never_cached_at_the_edge(tf: str) -> None:
    """CachingDisabled is a tenancy control here, not a performance choice.

    Caching an authenticated API response at the edge serves one tenant's data to the next
    requester of the same URL. There is no safe TTL for /api/*.
    """
    assert "4135ea2d-6df8-44a3-9df3-4b5a84be39ad" in tf, (
        "the API behaviours no longer use the AWS managed CachingDisabled cache policy "
        "(4135ea2d-6df8-44a3-9df3-4b5a84be39ad). Any caching TTL on /api/* can serve one "
        "tenant's authenticated response to another."
    )
    # And the API behaviours must not carry a TTL/forwarded_values shape, which is the
    # legacy alternative to a cache policy and cannot express "never cache" as safely.
    dynamic_block = re.search(
        r'dynamic "ordered_cache_behavior".*?\n  \}', tf, re.DOTALL
    )
    assert dynamic_block, "the dynamic ordered_cache_behavior block is gone"
    assert "forwarded_values" not in dynamic_block.group(0), (
        "the API behaviours use legacy forwarded_values instead of a cache policy. Mixing "
        "the two is rejected by the provider, and forwarded_values cannot reference the "
        "managed CachingDisabled policy."
    )


def test_the_authorization_header_reaches_the_api(tf: str) -> None:
    """AllViewerExceptHostHeader is load-bearing for authentication AND for websockets.

    Without it CloudFront strips Authorization, so every authenticated request arrives
    unauthenticated and the API answers 401 for everyone. It also forwards the WebSocket
    upgrade headers, while leaving Host as the origin's own so the ALB still routes to the
    right target group.
    """
    assert "b689b0a8-53d0-40ab-baf2-68738e2966ac" in tf, (
        "the API behaviours no longer use the AWS managed AllViewerExceptHostHeader origin "
        "request policy (b689b0a8-53d0-40ab-baf2-68738e2966ac). Without it the "
        "Authorization header is not forwarded and every authenticated request fails."
    )


def test_every_method_the_api_accepts_is_allowed_through(tf: str) -> None:
    """A read-only allowed_methods list silently breaks every mutation.

    CloudFront answers a disallowed method with 403 before the request reaches the origin,
    so a POST to /api/billing/checkout would fail at the edge with no API log line.
    """
    for method in ("DELETE", "GET", "HEAD", "OPTIONS", "PATCH", "POST", "PUT"):
        assert f'"{method}"' in tf, f"allowed_methods omits {method}"


def test_a_custom_alias_cannot_be_declared_without_its_certificate(tf: str) -> None:
    """The precondition exists because CloudFront's own error does not name the cause."""
    assert "cloudfront_aliases" in tf, "the distribution no longer declares aliases"
    assert "precondition" in tf, (
        "the alias/certificate precondition is gone. An alias without a matching us-east-1 "
        "ACM certificate is refused at apply time with a message that does not say why."
    )


def test_the_file_records_that_nothing_here_is_applied(tf: str) -> None:
    """The measurement, not an opinion: no state object exists for this backend.

    Kept as an assertion because the note is what stops the next person believing an
    `apply` here adopts production. If terraform IS adopted later, this test should fail
    and the note should be rewritten to say so -- that is the point.
    """
    assert "NOTHING IN THIS DIRECTORY IS APPLIED" in tf, (
        "the header note recording that terraform/ is unapplied has been removed. If that "
        "is now false, say what is true instead: the risk being guarded is somebody "
        "running `terraform import` + `apply` believing this file describes production."
    )
