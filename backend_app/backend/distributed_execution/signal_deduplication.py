# Global instance
_signal_deduplicator: Optional[SignalDeduplicator] = None


def get_signal_deduplicator() -> SignalDeduplicator:
    """Get or create signal deduplicator instance."""
    global _signal_deduplicator
    if _signal_deduplicator is None:
        _signal_deduplicator = SignalDeduplicator()
    return _signal_deduplicator
