"""
backend/optimization_engine.py — Research & Optimization Engine

PHASE Research & Optimization: Institutional-grade strategy optimization.

Architecture:
Builder → Compiler → Execution Graph → Strategy Package → Backtesting → Optimization → Validation → Deployment

This module sits AFTER Backtesting and BEFORE Deployment.
It uses the exact same Strategy Package generated by the compiler.
It reuses the existing backtesting, risk, and portfolio engines.
No duplicate execution runtime.
"""

import asyncio
import logging
from datetime import datetime, timezone, timedelta
from typing import Any, Dict, List, Optional, Tuple, Callable
from uuid import uuid4
from dataclasses import dataclass, field
from enum import Enum
import copy

