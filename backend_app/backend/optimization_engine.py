    def _calculate_strategy_score(
        self,
        optimization_results: List[OptimizationResult],
        walk_forward_results: List[WalkForwardResult],
        monte_carlo_results: List[MonteCarloResult]
    ) -> Dict[str, float]:
        """
        Calculate strategy quality score.
        
        PHASE J: Strategy Score
        Robustness, Stability, Risk, Return, Consistency, Complexity, Overfitting Risk.
        """
        score = {}
        
        # Return score (Sharpe ratio)
        if optimization_results:
            best_sharpe = max(r.metrics.get("sharpe_ratio", 0) for r in optimization_results)
            score["return"] = min(best_sharpe / 2.0, 1.0)  # Normalize to 0-1
        else:
            score["return"] = 0.0
        
        # Risk score (inverse of max drawdown)
        if optimization_results:
            avg_dd = np.mean([r.metrics.get("max_drawdown", 0) for r in optimization_results])
            score["risk"] = max(1.0 - avg_dd / 50.0, 0.0)  # Normalize
        else:
            score["risk"] = 0.0
        
        # Stability score (walk-forward consistency)
        if walk_forward_results:
            test_returns = [r.test_metrics.get("total_return_pct", 0) for r in walk_forward_results]
            if test_returns:
                score["stability"] = 1.0 - np.std(test_returns) / np.mean(np.abs(test_returns)) if np.mean(np.abs(test_returns)) > 0 else 0.0
            else:
                score["stability"] = 0.0
        else:
            score["stability"] = 0.0
        
        # Robustness score (Monte Carlo confidence interval width)
        if monte_carlo_results:
            ci_width = monte_carlo_results[0].confidence_intervals.get("total_return_pct", (0, 0))
            width = ci_width[1] - ci_width[0]
            score["robustness"] = max(1.0 - width / 100.0, 0.0)  # Normalize
        else:
            score["robustness"] = 0.5
        
        # Consistency score (win rate)
        if optimization_results:
            avg_wr = np.mean([r.metrics.get("win_rate", 0) for r in optimization_results])
            score["consistency"] = avg_wr / 100.0
        else:
            score["consistency"] = 0.0
        
        # Complexity score (number of parameters)
        score["complexity"] = 0.8  # Placeholder
        
        # Overfitting risk (train vs test performance difference)
        if walk_forward_results:
            train_returns = [r.train_metrics.get("total_return_pct", 0) for r in walk_forward_results]
            test_returns = [r.test_metrics.get("total_return_pct", 0) for r in walk_forward_results]
            if train_returns and test_returns:
                overfit = (np.mean(train_returns) - np.mean(test_returns)) / abs(np.mean(train_returns)) if np.mean(train_returns) != 0 else 0
                score["overfitting_risk"] = max(1.0 - abs(overfit), 0.0)
            else:
                score["overfitting_risk"] = 0.5
        else:
            score["overfitting_risk"] = 0.5
        
        # Overall score (weighted average)
        weights = {
            "return": 0.25,
            "risk": 0.20,
            "stability": 0.20,
            "robustness": 0.15,
            "consistency": 0.10,
            "complexity": 0.05,
            "overfitting_risk": 0.05
        }
        
        score["overall"] = sum(score[k] * weights[k] for k in weights) if score else 0.0
        
        return score
    
    def _detect_overfitting(
        self,
        optimization_results: List[OptimizationResult],
        walk_forward_results: List[WalkForwardResult]
    ) -> List[str]:
        """
        Detect overfitting.
        
        PHASE E: Overfitting Detection
        Compare training, validation, testing performance.
        """
        warnings = []
        
        if walk_forward_results:
            train_returns = [r.train_metrics.get("total_return_pct", 0) for r in walk_forward_results]
            test_returns = [r.test_metrics.get("total_return_pct", 0) for r in walk_forward_results]
            
            if train_returns and test_returns:
                avg_train = np.mean(train_returns)
                avg_test = np.mean(test_returns)
                
                # Overfitting: train much better than test
                if avg_train > 0 and avg_test > 0 and avg_train / avg_test > 1.5:
                    warnings.append("Overfitting detected: Training performance significantly higher than testing")
                
                # Underfitting: both poor
                if avg_train < 10 and avg_test < 10:
                    warnings.append("Underfitting detected: Low performance on both training and testing")
                
                # Instability: high variance
                if np.std(test_returns) > np.mean(np.abs(test_returns)):
                    warnings.append("Instability detected: High variance in test performance")
        
        return warnings


