def _data_engine_attr(attribute: str) -> Any:
    from backend_app.backend.data_seeking_engine import DataEngine

    return getattr(DataEngine, attribute, None)


def _ccxt_executor_attr(attribute: str) -> Any:
    from backend_app.backend.exchange_executor import CCXTExchangeExecutor

    return getattr(CCXTExchangeExecutor, attribute, None)


#: ``runtime_ref`` owner -> lookup. Engine owners are imported lazily so that declaring a
#: descriptor never drags CCXT into a process that only needs the schema.
_RUNTIME_OWNERS: Dict[str, Callable[[str], Any]] = {
    MODULE_REF: lambda attribute: globals().get(attribute),
    "DataEngine": _data_engine_attr,
    "CCXTExchangeExecutor": _ccxt_executor_attr,
}


def resolve_block_runtime(runtime_ref: str) -> Callable[..., Any]:
    """Resolve ``"block_specs.math_add"`` / ``"DataEngine.fetch_historical_ohlcv"`` etc.

    Raises ``AttributeError`` naming the offender so ``build_registry()`` fails startup
    rather than advertising a block it cannot run (Requirements 4.7, 4.8).
    """
    owner, _, attribute = str(runtime_ref).rpartition(".")
    lookup = _RUNTIME_OWNERS.get(owner)
    if lookup is None:
        raise AttributeError(
            f"runtime_ref '{runtime_ref}' names unknown owner '{owner}'; known owners are "
            f"{sorted(_RUNTIME_OWNERS)}"
        )
    target = lookup(attribute)
    if not callable(target):
        raise AttributeError(f"runtime_ref does not resolve to a callable: {runtime_ref}")
    return target


