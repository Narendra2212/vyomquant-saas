def _as_bool_array(value: Any) -> np.ndarray:
    """Coerce to a boolean series. NaN is not true: an undefined bar never signals."""
    if isinstance(value, np.ndarray) and value.dtype == np.bool_:
        return value
    array = _as_float_array(value)
    if array.ndim == 0:
        array = np.asarray([float(array)], dtype=np.float64)
    out = np.zeros(array.shape[0], dtype=bool)
    defined = ~np.isnan(array)
    out[defined] = array[defined] != 0.0
    return out


def _align_bool(operands: Sequence[Any], node_id: Optional[str]) -> List[np.ndarray]:
    arrays = [_as_bool_array(operand) for operand in operands]
    lengths = {int(a.shape[0]) for a in arrays}
    if len(lengths) > 1:
        where = f" at node '{node_id}'" if node_id else ""
        raise ValueError(
            f"boolean operands have mismatched lengths {sorted(lengths)}{where}"
        )
    return arrays


def _compare(
    op: Callable[..., np.ndarray], left: Any, right: Any, node_id: Optional[str]
) -> np.ndarray:
    """Comparator core: an undefined bar on either side reports False, never True."""
    a, b = _align((left, right), node_id)
    undefined = np.isnan(a) | np.isnan(b)
    with np.errstate(all="ignore"):
        out = op(np.where(undefined, 0.0, a), np.where(undefined, 0.0, b))
    out = np.asarray(out, dtype=bool)
    out[undefined] = False
    return out


def logic_and(*operands: Any, node_id: Optional[str] = None) -> np.ndarray:
    """True where every input is true on the same bar."""
    return _reduce(np.logical_and, _align_bool(operands, node_id))


def logic_or(*operands: Any, node_id: Optional[str] = None) -> np.ndarray:
    """True where at least one input is true on the same bar."""
    return _reduce(np.logical_or, _align_bool(operands, node_id))


def logic_not(a: Any, node_id: Optional[str] = None) -> np.ndarray:
    """Invert a condition."""
    return np.logical_not(_as_bool_array(a))


def logic_gt(left: Any, right: Any, node_id: Optional[str] = None) -> np.ndarray:
    """True where ``left > right``."""
    return _compare(np.greater, left, right, node_id)


def logic_lt(left: Any, right: Any, node_id: Optional[str] = None) -> np.ndarray:
    """True where ``left < right``."""
    return _compare(np.less, left, right, node_id)


def logic_gte(left: Any, right: Any, node_id: Optional[str] = None) -> np.ndarray:
    """True where ``left >= right``."""
    return _compare(np.greater_equal, left, right, node_id)


def logic_lte(left: Any, right: Any, node_id: Optional[str] = None) -> np.ndarray:
    """True where ``left <= right``."""
    return _compare(np.less_equal, left, right, node_id)


def logic_eq(left: Any, right: Any, node_id: Optional[str] = None) -> np.ndarray:
    """Equality within ``EQ_TOLERANCE``.

    Exact float equality on a computed series would essentially never fire, which reads as
    a silently dead strategy rather than a bug.
    """
    a, b = _align((left, right), node_id)
    undefined = np.isnan(a) | np.isnan(b)
    delta = np.abs(np.where(undefined, 0.0, a) - np.where(undefined, 0.0, b))
    out = delta <= EQ_TOLERANCE
    out[undefined] = False
    return out


def logic_neq(left: Any, right: Any, node_id: Optional[str] = None) -> np.ndarray:
    """Inequality outside ``EQ_TOLERANCE``; an undefined bar reports False."""
    a, b = _align((left, right), node_id)
    undefined = np.isnan(a) | np.isnan(b)
    delta = np.abs(np.where(undefined, 0.0, a) - np.where(undefined, 0.0, b))
    out = delta > EQ_TOLERANCE
    out[undefined] = False
    return out


def _cross(fast: Any, slow: Any, node_id: Optional[str], above: bool) -> np.ndarray:
    a, b = _align((fast, slow), node_id)
    out = np.zeros(a.shape[0], dtype=bool)
    if a.shape[0] < 2:
        return out
    defined = ~(np.isnan(a[:-1]) | np.isnan(b[:-1]) | np.isnan(a[1:]) | np.isnan(b[1:]))
    with np.errstate(all="ignore"):
        if above:
            crossed = (a[:-1] <= b[:-1]) & (a[1:] > b[1:])
        else:
            crossed = (a[:-1] >= b[:-1]) & (a[1:] < b[1:])
    out[1:] = defined & crossed
    return out


def logic_cross_above(fast: Any, slow: Any, node_id: Optional[str] = None) -> np.ndarray:
    """True only where ``fast`` strictly crossed above ``slow`` between ``t-1`` and ``t``.

    Closed bars only. A bar whose current or previous value is NaN reports False, so the
    warmup region never signals and a strategy never fires a trade on the first bar merely
    because an indicator was undefined before it.
    """
    return _cross(fast, slow, node_id, above=True)


def logic_cross_below(fast: Any, slow: Any, node_id: Optional[str] = None) -> np.ndarray:
    """Mirror of :func:`logic_cross_above`; closed bars only, silent through warmup."""
    return _cross(fast, slow, node_id, above=False)


def logic_between(
    value: Any,
    lower: Any,
    upper: Any,
    inclusive: bool = True,
    node_id: Optional[str] = None,
) -> np.ndarray:
    """True where ``value`` sits inside the band; an undefined bar reports False."""
    v, low, high = _align((value, lower, upper), node_id)
    undefined = np.isnan(v) | np.isnan(low) | np.isnan(high)
    safe_v = np.where(undefined, 0.0, v)
    safe_low = np.where(undefined, 0.0, low)
    safe_high = np.where(undefined, 0.0, high)
    if inclusive:
        out = (safe_v >= safe_low) & (safe_v <= safe_high)
    else:
        out = (safe_v > safe_low) & (safe_v < safe_high)
    out = np.asarray(out, dtype=bool)
    out[undefined] = False
    return out


def logic_if_then_else(
    condition: Any, then_value: Any, else_value: Any, node_id: Optional[str] = None
) -> np.ndarray:
    """Pick one of two series per bar according to ``condition``."""
    then_series, else_series = _align((then_value, else_value), node_id)
    mask = _as_bool_array(condition)
    if mask.shape[0] != then_series.shape[0]:
        raise ValueError(
            f"if_then_else condition length {mask.shape[0]} does not match value length "
            f"{then_series.shape[0]} at node '{node_id}'"
        )
    return _finite_or_nan(np.where(mask, then_series, else_series))


def logic_to_signal(
    condition: Any,
    direction: str,
    strength: float = 1.0,
    node_id: Optional[str] = None,
) -> np.ndarray:
    """Turn a boolean series into a SIGNAL series within ``[-1, 1]``.

    ``direction`` has no default in the descriptor: a silent "long" would trade the exact
    opposite of a short strategy.
    """
    normalised = str(direction).lower()
    if normalised not in ("long", "short"):
        raise ValueError(
            f"to_signal direction must be 'long' or 'short'; got {direction!r} at node "
            f"'{node_id}'"
        )
    magnitude = float(strength)
    if not math.isfinite(magnitude) or not 0.0 <= magnitude <= 1.0:
        raise ValueError(
            f"to_signal strength must be within [0, 1]; got {strength!r} at node "
            f"'{node_id}'"
        )
    mask = _as_bool_array(condition)
    out = np.zeros(mask.shape[0], dtype=np.float64)
    out[mask] = magnitude if normalised == "long" else -magnitude
    return out


