def _as_float_array(value: Any) -> np.ndarray:
    if value is None:
        raise ValueError("math operand is None; the compiler guarantees a wired input")
    if isinstance(value, bool):
        return np.asarray(1.0 if value else 0.0, dtype=np.float64)
    if isinstance(value, np.ndarray):
        return value.astype(np.float64, copy=False)
    return np.asarray(value, dtype=np.float64)


def _align(operands: Sequence[Any], node_id: Optional[str]) -> List[np.ndarray]:
    """Broadcast scalars onto the common series length; reject mismatched lengths.

    Timestamp alignment itself is a compile-time guarantee - by the time a series reaches a
    kernel it is already bar-aligned - so length equality is what remains checkable here.
    """
    arrays = [_as_float_array(operand) for operand in operands]
    lengths = {int(a.shape[0]) for a in arrays if a.ndim > 0}
    if len(lengths) > 1:
        where = f" at node '{node_id}'" if node_id else ""
        raise ValueError(
            f"math operands have mismatched lengths {sorted(lengths)}{where}; series must "
            "be equal-length and timestamp-aligned"
        )
    length = lengths.pop() if lengths else 1
    return [
        a if a.ndim > 0 else np.full(length, float(a), dtype=np.float64) for a in arrays
    ]


def _finite_or_nan(values: np.ndarray) -> np.ndarray:
    """Replace every non-finite value with NaN. No infinity leaves a kernel."""
    out = np.asarray(values, dtype=np.float64).copy()
    out[~np.isfinite(out)] = np.nan
    return out


def _record(
    issues: Optional[List[Dict[str, Any]]],
    node_id: Optional[str],
    code: str,
    mask: np.ndarray,
) -> None:
    if issues is None or not bool(np.any(mask)):
        return
    bars = np.flatnonzero(mask)
    issues.append(
        {
            "node_id": node_id,
            "code": code,
            "bar": int(bars[0]),
            "bars_affected": int(bars.size),
        }
    )


def _reduce(binary_op: Callable[..., np.ndarray], arrays: Sequence[np.ndarray]) -> np.ndarray:
    out = arrays[0]
    for array in arrays[1:]:
        out = binary_op(out, array)
    return out


_LOG_BASES: Dict[str, float] = {"e": math.e, "2": 2.0, "10": 10.0}


def safe_math_apply(
    op: str,
    operands: Sequence[Any],
    options: Optional[Mapping[str, Any]] = None,
    node_id: Optional[str] = None,
    issues: Optional[List[Dict[str, Any]]] = None,
) -> np.ndarray:
    """Apply ``op`` to ``operands`` under the design's numeric-safety contract.

    Preconditions
        Operand series are equal-length and timestamp-aligned; scalars broadcast.

    Postconditions
        The result contains only finite values or NaN - never ``+Inf``, ``-Inf`` or an
        overflowed value. Division by zero, negative roots and non-positive logarithms
        yield NaN with an issue recorded rather than an exception or a poisoned number. NaN
        propagates within the series so a warmup region stays NaN; the action boundary is
        what stops NaN from reaching an order.

    This is the vectorised equivalent of the per-bar loop in ``design.md`` -> Math blocks.
    The loop invariant there ("every already-written bar is finite-or-NaN") holds here
    because the terminal ``_finite_or_nan`` sweep is applied to the whole array before it
    is returned.
    """
    op = str(op).upper()
    opts = dict(options or {})

    # SHIFT is handled before operand-NaN propagation: shifting *creates* leading NaNs by
    # design, and a source bar's NaN state belongs to the source bar, not the target.
    if op == "SHIFT":
        (series,) = _align(operands, node_id)
        bars = int(opts.get("bars", 1))
        if bars < 0:
            raise ValueError(
                f"shift bars must be >= 0 (backward only); got {bars} at node '{node_id}'"
            )
        out = np.full(series.shape[0], np.nan, dtype=np.float64)
        if bars == 0:
            out[:] = series
        elif bars < series.shape[0]:
            out[bars:] = series[:-bars]
        return _finite_or_nan(out)

    arrays = _align(operands, node_id)
    nan_mask = np.zeros(arrays[0].shape[0], dtype=bool)
    for array in arrays:
        nan_mask |= np.isnan(array)

    with np.errstate(all="ignore"):
        if op == "ADD":
            raw = _reduce(np.add, arrays)
        elif op == "SUBTRACT":
            raw = arrays[0] - arrays[1]
        elif op == "MULTIPLY":
            raw = _reduce(np.multiply, arrays)
        elif op == "DIVIDE":
            numerator, denominator = arrays[0], arrays[1]
            unsafe = np.abs(denominator) < EPSILON
            _record(issues, node_id, "DIVISION_BY_ZERO", unsafe & ~nan_mask)
            raw = numerator / np.where(unsafe, np.nan, denominator)
        elif op == "MODULO":
            left, right = arrays[0], arrays[1]
            unsafe = np.abs(right) < EPSILON
            _record(issues, node_id, "MODULO_BY_ZERO", unsafe & ~nan_mask)
            raw = np.fmod(left, np.where(unsafe, np.nan, right))
        elif op == "MIN":
            raw = _reduce(np.minimum, arrays)
        elif op == "MAX":
            raw = _reduce(np.maximum, arrays)
        elif op == "ABS":
            raw = np.abs(arrays[0])
        elif op == "NEGATE":
            raw = -arrays[0]
        elif op == "ROUND":
            raw = np.round(arrays[0], int(opts.get("decimals", 2)))
        elif op == "FLOOR":
            raw = np.floor(arrays[0])
        elif op == "CEIL":
            raw = np.ceil(arrays[0])
        elif op == "SQRT":
            negative = arrays[0] < 0
            _record(issues, node_id, "NEGATIVE_ROOT", negative & ~nan_mask)
            raw = np.sqrt(np.where(negative, np.nan, arrays[0]))
        elif op == "LOG":
            base = opts.get("base", "e")
            divisor = _LOG_BASES.get(str(base))
            if divisor is None:
                raise ValueError(f"unsupported log base {base!r} at node '{node_id}'")
            non_positive = arrays[0] <= 0
            _record(issues, node_id, "NON_POSITIVE_LOG", non_positive & ~nan_mask)
            raw = np.log(np.where(non_positive, np.nan, arrays[0]))
            if divisor != math.e:
                raw = raw / math.log(divisor)
        elif op == "EXP":
            raw = np.exp(arrays[0])
        elif op == "CLAMP":
            lower, upper = opts.get("lower"), opts.get("upper")
            if lower is None or upper is None:
                raise ValueError(f"clamp needs lower and upper at node '{node_id}'")
            if float(lower) > float(upper):
                raise ValueError(
                    f"clamp lower ({lower}) exceeds upper ({upper}) at node '{node_id}'"
                )
            raw = np.clip(arrays[0], float(lower), float(upper))
        elif op == "IDENTITY":
            raw = arrays[0]
        else:
            raise ValueError(f"unknown math op '{op}' at node '{node_id}'")

    # Requirement 20.4 lists "an arithmetic overflow" alongside division by zero, the
    # negative root and the non-positive logarithm: all four write NaN for the bar AND
    # record the condition. The three named cases are recorded at their own branch
    # because only that branch knows why the bar was undefined; an overflow has no
    # branch of its own - ``exp(800)``, ``1e300 * 1e300`` and a runaway ``ADD`` all reach
    # here as an infinity - so it is detected once, on the result, for every op. A bar
    # already NaN'd by a named branch is not an infinity by the time it arrives, so the
    # two never double-report the same bar.
    raw = np.asarray(raw, dtype=np.float64)
    _record(issues, node_id, "ARITHMETIC_OVERFLOW", np.isinf(raw) & ~nan_mask)

    result = _finite_or_nan(raw)
    result[nan_mask] = np.nan
    return result


