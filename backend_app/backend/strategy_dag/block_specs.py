@dataclass(frozen=True)
class ParamSpec:
    """Declarative parameter contract.

    The UI form generator and the backend validator read this same object, so a form can
    never offer a value the backend rejects and the backend never assumes the form checked
    (Requirements 5.1, 5.7).

    ``forward_to_runtime`` is False for parameters the runtime callable does not take as a
    keyword argument - ``mode`` selects which ``DataEngine`` call the executor makes, it is
    not an argument to it.
    """

    key: str
    label: str
    type: ParamType
    required: bool = True
    default: Any = None
    min: Optional[float] = None
    max: Optional[float] = None
    step: Optional[float] = None
    options: Optional[Tuple[Any, ...]] = None
    unit: Optional[str] = None
    example: Any = None
    help: str = ""
    depends_on: Tuple[str, ...] = ()
    affects_warmup: bool = False
    forward_to_runtime: bool = True
    #: Where a SELECT / MULTISELECT option set comes from when it cannot be enumerated
    #: at declaration time, because it depends on the graph rather than on the block -
    #: ``feat_select``'s columns are the upstream feature matrix's columns. A declared
    #: source is the only way to omit ``options``, so "resolved from the graph" stays
    #: distinguishable from "option set forgotten".
    options_source: Optional[str] = None

    def __post_init__(self) -> None:
        if self.key in FORBIDDEN_PARAM_KEYS:
            raise ValueError(
                f"Param '{self.key}' is forbidden in a strategy definition (SB-06); "
                "exchange identity belongs to the deployment binding"
            )
        if (
            self.type in (ParamType.SELECT, ParamType.MULTISELECT)
            and not self.options
            and not self.options_source
        ):
            raise ValueError(
                f"Param '{self.key}' is {self.type.value} but declares neither options "
                "nor an options_source"
            )
        if self.min is not None and self.max is not None and self.min > self.max:
            raise ValueError(f"Param '{self.key}' declares min > max")
        if self.key in NO_DEFAULT_PARAMS:
            if self.default is not None:
                raise ValueError(
                    f"Param '{self.key}' changes trading behaviour and must be published "
                    "with no default (Requirement 5.4)"
                )
            if not self.required:
                raise ValueError(
                    f"Param '{self.key}' changes trading behaviour and must be published "
                    "as required (Requirement 5.4)"
                )

    def to_dict(self) -> Dict[str, Any]:
        return {
            "key": self.key,
            "label": self.label,
            "type": self.type.value,
            "required": self.required,
            "default": self.default,
            "min": self.min,
            "max": self.max,
            "step": self.step,
            "options": list(self.options) if self.options else None,
            "options_source": self.options_source,
            "unit": self.unit,
            "example": self.example,
            "help": self.help,
            "depends_on": list(self.depends_on),
            "affects_warmup": self.affects_warmup,
        }


@dataclass(frozen=True)
class BlockSpec:
    """Machine-readable descriptor for one DATA, MATH, LOGIC or ACTION block.

    Field names mirror ``BlockDescriptor`` in ``design.md`` so ``registry.py`` can adapt a
    ``BlockSpec`` without renaming anything, exactly as it adapts ``IndicatorSpec``,
    ``FeatureSpec`` and ``ModelSpec``.
    """

    block_id: str
    display_name: str
    category: BlockCategory
    description: str
    inputs: Tuple[Port, ...]
    outputs: Tuple[Port, ...]
    params: Tuple[ParamSpec, ...]
    warmup_fn: Callable[[Mapping[str, Any]], int]
    runtime_ref: str
    allowed_predecessor_categories: Tuple[BlockCategory, ...] = ()
    allowed_successor_categories: Tuple[BlockCategory, ...] = ()
    execution_semantics: ExecutionSemantics = ExecutionSemantics.SERIES_MAP
    #: Stream counterpart of ``runtime_ref`` for a block whose primary reference is the
    #: historical or snapshot call. Asserted callable alongside ``runtime_ref``.
    streaming_runtime_ref: Optional[str] = None
    serialization: Serialization = Serialization.NONE
    leakage_risk: LeakageRisk = LeakageRisk.NONE
    version: str = "1.0.0"
    capability_flags: Tuple[str, ...] = ()
    #: Cross-field rules that ranges and enums cannot express.
    validate: Optional[Callable[[Mapping[str, Any]], List[str]]] = None
    #: Non-contractual extras the compiler and executor need: ``order_type``, ``side``,
    #: ``intent``, ``operator``. Excluded from parameter validation.
    metadata: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        _reject_duplicates(self.block_id, "input port", [p.name for p in self.inputs])
        _reject_duplicates(self.block_id, "output port", [p.name for p in self.outputs])
        _reject_duplicates(self.block_id, "param", [p.key for p in self.params])

        terminal = self.execution_semantics is ExecutionSemantics.TERMINAL
        if terminal and self.outputs:
            raise ValueError(
                f"Block '{self.block_id}' is TERMINAL and must declare no output ports"
            )
        if terminal and self.allowed_successor_categories:
            raise ValueError(
                f"Block '{self.block_id}' is TERMINAL and must declare an empty successor "
                "set; nothing can be chained after an order"
            )
        if not terminal and not self.outputs:
            raise ValueError(
                f"Block '{self.block_id}' declares no output ports but is not TERMINAL"
            )
        if self.category is BlockCategory.ACTION:
            if not terminal:
                raise ValueError(f"ACTION block '{self.block_id}' must be TERMINAL")
            offenders = [p.key for p in self.params if p.key in FORBIDDEN_ACTION_PARAM_KEYS]
            if offenders:
                raise ValueError(
                    f"ACTION block '{self.block_id}' declares traded-asset params "
                    f"{offenders}; the traded symbol is resolved from the DATA node in the "
                    "action's upstream closure (Requirement 12.8)"
                )

    # -- derived views ----------------------------------------------------
    @property
    def is_terminal(self) -> bool:
        return self.execution_semantics is ExecutionSemantics.TERMINAL

    def input_port(self, name: str) -> Optional[Port]:
        return next((p for p in self.inputs if p.name == name), None)

    def output_port(self, name: str) -> Optional[Port]:
        return next((p for p in self.outputs if p.name == name), None)

    def param(self, key: str) -> Optional[ParamSpec]:
        return next((p for p in self.params if p.key == key), None)

    def required_params(self) -> Tuple[ParamSpec, ...]:
        return tuple(p for p in self.params if p.required)

    def defaults(self) -> Dict[str, Any]:
        """Parameter map a freshly dropped node starts with.

        Keys whose declared default is ``None`` are present and empty on purpose: the
        inspector renders them blank and blocking until the author sets them.
        """
        return {p.key: p.default for p in self.params}

    def runtime_kwargs(self, params: Optional[Mapping[str, Any]] = None) -> Dict[str, Any]:
        """The subset of params the runtime callable actually accepts."""
        supplied = dict(params or {})
        resolved: Dict[str, Any] = {}
        for spec in self.params:
            if not spec.forward_to_runtime:
                continue
            if spec.key in supplied and supplied[spec.key] is not None:
                resolved[spec.key] = supplied[spec.key]
            elif spec.default is not None:
                resolved[spec.key] = spec.default
        return resolved

    def runtime_refs(self) -> Tuple[str, ...]:
        """Every runtime reference this descriptor advertises."""
        refs = [self.runtime_ref]
        if self.streaming_runtime_ref:
            refs.append(self.streaming_runtime_ref)
        return tuple(refs)

    def resolve_runtime(self) -> Callable[..., Any]:
        return resolve_block_runtime(self.runtime_ref)

    def warmup(self, params: Optional[Mapping[str, Any]] = None) -> int:
        resolved = self.defaults()
        if params:
            resolved.update({k: v for k, v in params.items() if v is not None})
        return int(self.warmup_fn(resolved))

    def to_dict(self) -> Dict[str, Any]:
        return {
            "block_id": self.block_id,
            "display_name": self.display_name,
            "category": self.category.value,
            "description": self.description,
            "inputs": [p.to_dict() for p in self.inputs],
            "outputs": [p.to_dict() for p in self.outputs],
            "params": [p.to_dict() for p in self.params],
            "allowed_predecessor_categories": [
                c.value for c in self.allowed_predecessor_categories
            ],
            "allowed_successor_categories": [
                c.value for c in self.allowed_successor_categories
            ],
            "execution_semantics": self.execution_semantics.value,
            "runtime_ref": self.runtime_ref,
            "streaming_runtime_ref": self.streaming_runtime_ref,
            "serialization": self.serialization.value,
            "leakage_risk": self.leakage_risk.value,
            "version": self.version,
            "capability_flags": list(self.capability_flags),
            "metadata": dict(self.metadata),
        }


def _reject_duplicates(block_id: str, kind: str, names: Sequence[str]) -> None:
    seen = set()
    for name in names:
        if name in seen:
            raise ValueError(f"Block '{block_id}' declares duplicate {kind} '{name}'")
        seen.add(name)


