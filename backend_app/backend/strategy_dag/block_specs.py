#: order type value -> the descriptor variants it produces. Keyed by the *value* of the
#: real ``exchange_executor.OrderType`` members; coverage is asserted, never assumed.
_ACTION_VARIANTS: Dict[str, Tuple[Callable[[], Tuple[BlockSpec, ...]], ...]] = {
    "market": (_market_actions,),
    "limit": (_limit_actions,),
    "stop_market": (_stop_market_actions,),
    "stop_limit": (_stop_limit_actions,),
    "take_profit_market": (_take_profit_market_actions,),
    "take_profit_limit": (_take_profit_limit_actions,),
}


def supported_order_types() -> Tuple[Any, ...]:
    """The real ``exchange_executor.OrderType`` members, imported lazily.

    Imported here rather than at module scope so that declaring a descriptor does not drag
    CCXT into a process that only needs the schema, and so this module stays importable in
    an environment where CCXT is absent.
    """
    from backend_app.backend.exchange_executor import OrderType

    return tuple(OrderType)


def _assert_order_type_coverage(order_types: Sequence[Any]) -> None:
    """Every supported order type must produce at least one descriptor, and vice versa.

    This is the structural guard behind Requirement 4.10: the palette cannot advertise an
    order type the execution layer cannot place, and cannot silently omit one the execution
    layer gained.
    """
    supported = {str(getattr(item, "value", item)) for item in order_types}
    declared = set(_ACTION_VARIANTS)
    missing = sorted(supported - declared)
    if missing:
        raise ValueError(
            f"exchange_executor.OrderType supports {missing} but no ACTION descriptor "
            "variant is declared for them; the palette would silently omit a placeable "
            "order type"
        )
    extra = sorted(declared - supported)
    if extra:
        raise ValueError(
            f"ACTION descriptor variants {extra} name order types exchange_executor does "
            "not support; the palette would advertise an unplaceable order"
        )


def action_specs(order_types: Optional[Sequence[Any]] = None) -> Tuple[BlockSpec, ...]:
    """Every ACTION descriptor, generated from the real ``OrderType`` enum.

    Order types are read from ``exchange_executor`` rather than restated here, so an order
    type the executor does not support cannot appear in the palette (Requirement 4.10).
    """
    resolved = tuple(order_types) if order_types is not None else supported_order_types()
    _assert_order_type_coverage(resolved)
    specs: List[BlockSpec] = []
    for order_type in resolved:
        specs.extend(action_descriptors_for(order_type))
    return tuple(specs)


