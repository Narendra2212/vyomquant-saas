def _validate_clamp(params: Mapping[str, Any]) -> List[str]:
    """Ranges cannot express "lower < upper"; this hook can."""
    lower, upper = params.get("lower"), params.get("upper")
    if lower is None or upper is None:
        return []
    if float(lower) >= float(upper):
        return [f"lower ({lower}) must be less than upper ({upper})"]
    return []


