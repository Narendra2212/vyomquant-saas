#: The three families that need no engine import, indexed for cheap lookup. ACTION is not
#: included because generating it reads ``exchange_executor.OrderType``; use
#: :func:`all_block_specs` or :func:`action_specs` for the full set.
STATIC_SPECS: Tuple[BlockSpec, ...] = DATA_SPECS + MATH_SPECS + LOGIC_SPECS

STATIC_SPECS_BY_ID: Dict[str, BlockSpec] = {spec.block_id: spec for spec in STATIC_SPECS}

if len(STATIC_SPECS_BY_ID) != len(STATIC_SPECS):
    _seen: Dict[str, int] = {}
    for _spec in STATIC_SPECS:
        _seen[_spec.block_id] = _seen.get(_spec.block_id, 0) + 1
    raise ValueError(
        "duplicate block_id in block_specs: "
        f"{sorted(block_id for block_id, count in _seen.items() if count > 1)}"
    )


def all_block_specs(order_types: Optional[Sequence[Any]] = None) -> Tuple[BlockSpec, ...]:
    """DATA + MATH + LOGIC + ACTION, in palette order.

    ``registry.build_registry()`` consumes this alongside ``INDICATOR_SPECS``,
    ``FEATURE_SPECS`` and ``MODEL_SPECS``. Every ``block_id`` is unique across the four
    families; the assertion below fails loudly rather than letting one family shadow
    another's block.
    """
    specs = DATA_SPECS + MATH_SPECS + LOGIC_SPECS + action_specs(order_types)
    seen: Dict[str, BlockSpec] = {}
    for spec in specs:
        if spec.block_id in seen:
            raise ValueError(
                f"duplicate block_id '{spec.block_id}' across block_specs families"
            )
        seen[spec.block_id] = spec
    return specs


def get_block_spec(block_id: str) -> BlockSpec:
    """Look up one descriptor. Raises ``KeyError`` for an unknown block.

    ACTION descriptors are generated on demand, so this consults the static index first and
    falls back to the generated ACTION set.
    """
    spec = STATIC_SPECS_BY_ID.get(block_id)
    if spec is not None:
        return spec
    for candidate in action_specs():
        if candidate.block_id == block_id:
            return candidate
    raise KeyError(block_id)


def specs_in_category(category: BlockCategory) -> Tuple[BlockSpec, ...]:
    """Every descriptor this module declares for ``category``."""
    if category is BlockCategory.ACTION:
        return action_specs()
    return tuple(spec for spec in STATIC_SPECS if spec.category is category)


def validate_block_params(spec: BlockSpec, params: Mapping[str, Any]) -> List[str]:
    """Check one node's params against its descriptor.

    Returns human-readable problems; an empty list means the params are acceptable. Required
    flags, option sets and ranges come from the same ``ParamSpec`` objects the UI form was
    generated from, so the form and the backend cannot diverge (Requirement 5.7). Each
    message names the field, the expected constraint and the received value (Requirement
    5.8).
    """
    issues: List[str] = []

    for param in spec.params:
        value = params.get(param.key)

        if value is None:
            if param.required and param.default is None:
                issues.append(
                    f"{spec.block_id}.{param.key} is required and has no default; "
                    f"received {value!r}"
                )
            continue

        values = list(value) if isinstance(value, (list, tuple)) else [value]

        if param.options is not None:
            unknown = [item for item in values if item not in param.options]
            if unknown:
                issues.append(
                    f"{spec.block_id}.{param.key} expects one of {list(param.options)}; "
                    f"received {unknown}"
                )

        if param.type in (ParamType.NUMBER, ParamType.INTEGER, ParamType.MULTISELECT):
            for item in values:
                if isinstance(item, bool) or not isinstance(item, (int, float)):
                    if param.type is not ParamType.MULTISELECT:
                        issues.append(
                            f"{spec.block_id}.{param.key} expects a "
                            f"{param.type.value.lower()}; received {item!r}"
                        )
                    continue
                if param.type is ParamType.INTEGER and float(item) != int(item):
                    issues.append(
                        f"{spec.block_id}.{param.key} expects a whole number; "
                        f"received {item!r}"
                    )
                if param.min is not None and item < param.min:
                    issues.append(
                        f"{spec.block_id}.{param.key} expects at least {param.min}; "
                        f"received {item!r}"
                    )
                if param.max is not None and item > param.max:
                    issues.append(
                        f"{spec.block_id}.{param.key} expects at most {param.max}; "
                        f"received {item!r}"
                    )

        if param.type is ParamType.BOOLEAN and not isinstance(value, bool):
            issues.append(
                f"{spec.block_id}.{param.key} expects a boolean; received {value!r}"
            )

    unknown_keys = sorted(
        key for key in params if spec.param(key) is None
    )
    if unknown_keys:
        issues.append(
            f"{spec.block_id} received parameters it does not declare: {unknown_keys}"
        )

    if spec.validate is not None:
        issues.extend(f"{spec.block_id}: {problem}" for problem in spec.validate(params))

    return issues
