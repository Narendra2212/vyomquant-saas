"""
backend/strategy_dag/block_specs.py - DATA, MATH, LOGIC and ACTION block descriptors.

The four block families that have no engine module of their own. INDICATOR descriptors
live in ``indicators_backend.INDICATOR_SPECS``, FEATURE_ENGINEERING in
``feature_engineering.FEATURE_SPECS`` and ML_DL in ``ml_models.MODEL_SPECS``; the
remaining four are declared here so ``registry.build_registry()`` can assemble all seven
categories from real descriptors instead of a hand-maintained palette list (SB-03/SB-04).

Exposes
-------
``ParamSpec`` / ``BlockSpec``   descriptor contract, field-for-field with
                                ``design.md`` -> Descriptor contract
``MATH_SPECS``                  18 arithmetic blocks
``LOGIC_SPECS``                 14 boolean / comparison / signal blocks
``DATA_SPECS``                  ``ohlcv_feed``, ``live_ticker``, ``orderbook_imbalance``
``action_descriptors_for(ot)``  the ACTION factory, one order type in
``action_specs()``              every ACTION descriptor, generated from
                                ``exchange_executor.OrderType``
``all_block_specs()``           the four families concatenated
``resolve_block_runtime(ref)``  ``runtime_ref`` -> callable, raises when it cannot
``validate_block_params(...)``  declarative + cross-field parameter checks

Design rules this module encodes
--------------------------------
* **SB-06.** ``ohlcv_feed`` declares no ``exchange`` parameter, and ``symbol`` /
  ``timeframe`` are required with ``default=None``. There is no silent ``"BTC/USDT"`` and
  no silent ``"15m"``. Exchange identity exists only on a deployment binding.
* **Requirement 12.8.** No ACTION descriptor carries a traded-asset parameter. The traded
  symbol is resolved by the compiler from the DATA node in the action's upstream closure.
* **Requirement 5.4 / financial safety.** ``quantity_type`` and ``quantity`` are required
  with no default on every ACTION descriptor, as are ``price`` / ``trigger_price`` /
  ``limit_price`` where the order type uses them. A silent default position size is a
  financial-safety defect, so a graph that omits one cannot be saved.
* **Requirement 4.10.** ACTION descriptors are generated by iterating the real
  ``exchange_executor.OrderType``. Adding an order type to the executor without adding a
  descriptor variant here fails loudly (``_assert_order_type_coverage``); the palette can
  never advertise an order type the execution layer cannot place, nor silently omit one.
* **Terminal actions.** Every ACTION descriptor has no output ports and an empty
  ``allowed_successor_categories``, so nothing can be chained after an order.

Runtime references
------------------
Every ``runtime_ref`` resolves to a callable that exists today - the registry asserts this
at startup and refuses to advertise a block it cannot run:

* MATH / LOGIC / order-book imbalance -> the kernels defined in this module. They are pure
  array functions with the numeric firewall from ``design.md`` -> Math blocks applied
  (NaN propagates, division by zero / negative roots / non-positive logs yield NaN, and no
  infinity ever leaves a kernel). ``MathExecutor`` and ``LogicExecutor`` delegate to them
  rather than reimplementing arithmetic, exactly as ``IndicatorExecutor`` delegates to
  ``indicators_backend``.
* DATA -> ``data_seeking_engine.DataEngine`` methods, the platform's real market data
  access. ``streaming_runtime_ref`` names the stream counterpart of a block whose primary
  reference is the historical or snapshot call; both are asserted callable.
* ACTION -> ``exchange_executor.CCXTExchangeExecutor.place_order``, the real order path.
  Order parameters are advisory intent only: ``execution_guard``, ``risk_engine`` and
  ``execution_engine`` re-validate quantity, notional, precision, balance, position and
  risk limits at execution time and can refuse any intent.

Purity
------
Importing this module pulls in nothing heavier than NumPy. ``data_seeking_engine`` and
``exchange_executor`` are imported lazily, inside the resolver and the ACTION factory, so
declaring a descriptor never drags CCXT into a process that only needs the schema.
"""

