def order_book_imbalance(
    order_book: Mapping[str, Any], depth: int = 10
) -> Dict[str, float]:
    """Top-of-book volume imbalance from one L2 order book snapshot.

    ``order_book`` is a CCXT-shaped mapping with ``bids`` and ``asks`` as
    ``[[price, amount], ...]`` sorted best-first, which is what
    ``DataEngine.stream_order_book`` and ``DataEngine.fetch_order_book_snapshot`` yield.

    Returns one entry per output port. ``imbalance`` is
    ``(bid_volume - ask_volume) / (bid_volume + ask_volume)`` over the top ``depth``
    levels, so it lies in ``[-1, 1]``, and is NaN when both sides are empty - an empty book
    is unknown, not balanced.
    """
    levels = max(1, int(depth))
    bid_volume = _sum_levels(order_book.get("bids"), levels)
    ask_volume = _sum_levels(order_book.get("asks"), levels)
    total = bid_volume + ask_volume
    imbalance = float("nan") if total < EPSILON else (bid_volume - ask_volume) / total
    return {
        "imbalance": imbalance,
        "bid_volume": bid_volume,
        "ask_volume": ask_volume,
    }


def _sum_levels(levels: Any, depth: int) -> float:
    if not levels:
        return 0.0
    total = 0.0
    for level in list(levels)[:depth]:
        try:
            amount = float(level[1])
        except (TypeError, ValueError, IndexError):
            continue
        if math.isfinite(amount) and amount > 0:
            total += amount
    return total


