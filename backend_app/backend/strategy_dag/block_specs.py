def _validate_ohlcv_history(params: Mapping[str, Any]) -> List[str]:
    """Historical mode needs a coherent window; ranges alone cannot say that."""
    issues: List[str] = []
    mode = params.get("mode")
    start, end = params.get("history_start"), params.get("history_end")
    if mode == "historical" and not start:
        issues.append("history_start is required when mode is 'historical'")
    if start and end and str(end) < str(start):
        issues.append(f"history_end ({end}) precedes history_start ({start})")
    return issues


